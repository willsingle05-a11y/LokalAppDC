import { writeFile } from "node:fs/promises";

const urls = process.argv.slice(2).filter(value => /^https?:\/\//i.test(value));
const outputArgIndex = process.argv.indexOf("--sql");
const outputFile = outputArgIndex >= 0 ? process.argv[outputArgIndex + 1] : "";
const targetSql = outputFile || `${process.env.TEMP || "."}\\lokal-thingstododc-description-updates.sql`;

function decodeHtml(value = "") {
  return String(value)
    .replace(/&#(\d+);/g, (_, code) => String.fromCharCode(Number(code)))
    .replace(/&#x([0-9a-f]+);/gi, (_, code) => String.fromCharCode(parseInt(code, 16)))
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, '"')
    .replace(/&#8217;/g, "'")
    .replace(/&#8220;|&#8221;/g, '"')
    .replace(/&#8211;|&#8212;/g, "-")
    .replace(/&hellip;/g, "...")
    .replace(/&nbsp;/g, " ")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .trim();
}

function stripTags(value = "") {
  return decodeHtml(String(value)
    .replace(/<script[\s\S]*?<\/script>/gi, " ")
    .replace(/<style[\s\S]*?<\/style>/gi, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/\s+/g, " "));
}

async function fetchText(url) {
  const response = await fetch(url, { headers: { "User-Agent": "LokalDC/1.0 event description enrichment" } });
  if (!response.ok) throw new Error(`${url} returned ${response.status}`);
  return response.text();
}

function externalIdFromUrl(url) {
  return String(url).replace(/^https?:\/\/thingstododc\.com\/event\//, "").replace(/\/$/, "");
}

function extractFullDescription(html) {
  const pageText = stripTags(html);
  const detailsIndex = pageText.indexOf("Details");
  if (detailsIndex < 0) return "";
  const afterDetails = pageText.slice(detailsIndex + "Details".length);
  const markerIndexes = ["Suggested Attire", "Map", "Related Events", "Purchase", "BUY NOW"]
    .map(marker => afterDetails.indexOf(marker))
    .filter(index => index > 40);
  const endIndex = markerIndexes.length ? Math.min(...markerIndexes) : afterDetails.length;
  return afterDetails.slice(0, endIndex)
    .replace(/\s*Courtesy of\s+Thing to do\s*$/i, "")
    .replace(/\s+/g, " ")
    .trim();
}

function sqlString(value) {
  return `'${String(value || "").replace(/'/g, "''")}'`;
}

if (!urls.length) throw new Error("Pass one or more ThingsToDoDC event URLs.");

const rows = [];
for (const url of urls) {
  const description = extractFullDescription(await fetchText(url));
  if (!description || /\[\s*\.\.\.\s*\]/.test(description)) {
    throw new Error(`Could not extract full description for ${url}`);
  }
  rows.push({ external_id: externalIdFromUrl(url), description });
}

const values = rows.map(row => `(${sqlString(row.external_id)}, ${sqlString(row.description)})`).join(",\n  ");
const sql = `-- Refresh full ThingsToDoDC descriptions. Generated by tools/enrich-thingstododc-descriptions.mjs.
update public.events e
set description = updates.description,
    raw_json = coalesce(e.raw_json, '{}'::jsonb) || jsonb_build_object('full_description', updates.description),
    updated_at = now()
from (values
  ${values}
) as updates(external_id, description)
where e.source = 'thingstododc'
  and e.external_id = updates.external_id;
`;

await writeFile(targetSql, sql);
console.log(JSON.stringify({
  outputFile: targetSql,
  updatedRows: rows.map(row => ({ external_id: row.external_id, descriptionLength: row.description.length }))
}, null, 2));
